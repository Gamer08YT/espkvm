# Writes vectors.h for test_webrtc.c: SRTP, SRTCP and STUN worked out by a
# second, independent implementation (this one, on the `cryptography` package),
# so the C is checked against something other than itself. The SRTP key
# derivation is also checked against RFC 3711 B.3 here.
#
#   python3 gen_vectors.py > vectors.h
import hashlib
import hmac
import struct
import zlib

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def aes_ctr(key, iv, data):
    e = Cipher(algorithms.AES(key), modes.CTR(iv)).encryptor()
    return e.update(data) + e.finalize()


def kdf(mk, ms, label, n):
    iv = bytearray(ms + b"\0\0")
    iv[7] ^= label
    return aes_ctr(mk, bytes(iv), b"\0" * n)


# RFC 3711 B.3
mk = bytes.fromhex("E1F97A0D3E018BE0D64FA32C06DE4139")
ms = bytes.fromhex("0EC675AD498AFEEBB6960B3AABE6")
assert kdf(mk, ms, 0, 16) == bytes.fromhex("C61E7A93744F39EE10734AFE3FF7A087")
assert kdf(mk, ms, 2, 14) == bytes.fromhex("30CBBC08863D8C85D49DB34A9AE1")
assert kdf(mk, ms, 1, 20)[:16] == bytes.fromhex("CEBE321F6FF7716B6FD4AB49AF256A15")


def iv_for(salt, ssrc, index):
    iv = bytearray(salt + b"\0\0")
    for i in range(4):
        iv[4 + i] ^= ssrc[i]
    for i in range(6):
        iv[13 - i] ^= (index >> (8 * i)) & 0xFF
    return bytes(iv)


def srtp(mk, ms, pkt, roc):
    k, a, s = kdf(mk, ms, 0, 16), kdf(mk, ms, 1, 20), kdf(mk, ms, 2, 14)
    seq = struct.unpack(">H", pkt[2:4])[0]
    # The header stays clear: CSRCs and any header extension included.
    hl = 12 + 4 * (pkt[0] & 0x0F)
    if pkt[0] & 0x10:
        hl += 4 + 4 * struct.unpack(">H", pkt[hl + 2:hl + 4])[0]
    ct = pkt[:hl] + aes_ctr(k, iv_for(s, pkt[8:12], (roc << 16) | seq), pkt[hl:])
    tag = hmac.new(a, ct + struct.pack(">I", roc), hashlib.sha1).digest()[:10]
    return ct + tag


def srtcp(mk, ms, pkt, index):
    k, a, s = kdf(mk, ms, 3, 16), kdf(mk, ms, 4, 20), kdf(mk, ms, 5, 14)
    ct = pkt[:8] + aes_ctr(k, iv_for(s, pkt[4:8], index), pkt[8:])
    ct += struct.pack(">I", 0x80000000 | index)
    return ct + hmac.new(a, ct, hashlib.sha1).digest()[:10]


def carr(name, b):
    body = ", ".join("0x%02x" % x for x in b)
    return "static const uint8_t %s[%d] = {%s};" % (name, len(b), body)


out = ["/* Generated by gen_vectors.py - do not edit. */", "#pragma once", "#include <stdint.h>"]
out.append(carr("V_MK", mk))
out.append(carr("V_MS", ms))

rtp = bytes.fromhex("80 60 12 34 00 00 30 39 de ad be ef".replace(" ", "")) + bytes(range(100))
out.append(carr("V_RTP", rtp))
out.append(carr("V_SRTP", srtp(mk, ms, rtp, 0)))
# The same packet after the sequence number wrapped once.
rtp2 = bytearray(rtp)
rtp2[2:4] = b"\x00\x05"
out.append(carr("V_RTP_WRAP", bytes(rtp2)))
out.append(carr("V_SRTP_WRAP", srtp(mk, ms, bytes(rtp2), 1)))

# With the playout-delay extension (id 5, min = max = 0), as the device sends it.
rtp3 = bytearray(rtp)
rtp3[0] = 0x90
rtp3 = bytes(rtp3[:12]) + bytes.fromhex("bede0001" "52000000") + rtp[12:]
out.append(carr("V_RTP_EXT", rtp3))
out.append(carr("V_SRTP_EXT", srtp(mk, ms, rtp3, 0)))

# A PLI: PSFB (206), FMT 1, from the browser's SSRC about ours.
rtcp = bytes.fromhex("81ce0002" "11223344" "deadbeef")
out.append(carr("V_RTCP", rtcp))
out.append(carr("V_SRTCP", srtcp(mk, ms, rtcp, 0)))
out.append(carr("V_SRTCP7", srtcp(mk, ms, rtcp, 7)))

# STUN: a Binding request from a browser, signed with our password.
pwd = b"device-ice-password-123456"
txid = bytes(range(1, 13))


def attr(t, v):
    pad = (4 - len(v) % 4) % 4
    return struct.pack(">HH", t, len(v)) + v + b"\0" * pad


body = attr(0x0006, b"dev1:brws") + attr(0x0024, struct.pack(">I", 1853766911))
body += attr(0x802A, b"\x01\x02\x03\x04\x05\x06\x07\x08") + attr(0x0025, b"")
hdr = struct.pack(">HHI", 0x0001, len(body) + 24, 0x2112A442) + txid
mi = hmac.new(pwd, hdr + body, hashlib.sha1).digest()
body += attr(0x0008, mi)
hdr = struct.pack(">HHI", 0x0001, len(body) + 8, 0x2112A442) + txid
fp = (zlib.crc32(hdr + body) ^ 0x5354554E) & 0xFFFFFFFF
body += attr(0x8028, struct.pack(">I", fp))
out.append(carr("V_STUN_PWD", pwd))
out.append(carr("V_STUN_REQ", hdr + body))

# Our answer to it, from 192.168.1.20:50000.
ip, port = bytes([192, 168, 1, 20]), 50000
xport = port ^ 0x2112
xip = bytes(a ^ b for a, b in zip(ip, b"\x21\x12\xa4\x42"))
rb = attr(0x0020, b"\x00\x01" + struct.pack(">H", xport) + xip)
rh = struct.pack(">HHI", 0x0101, len(rb) + 24 + 8, 0x2112A442) + txid
rmi_hdr = struct.pack(">HHI", 0x0101, len(rb) + 24, 0x2112A442) + txid
rb += attr(0x0008, hmac.new(pwd, rmi_hdr + rb, hashlib.sha1).digest())
rb += attr(0x8028, struct.pack(">I", (zlib.crc32(rh + rb) ^ 0x5354554E) & 0xFFFFFFFF))
out.append(carr("V_STUN_RESP", rh + rb))

print("\n".join(out))
